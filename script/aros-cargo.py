#!/usr/bin/env python3
"""Run cargo for native AROS with an installed AROS Rust SDK and crate store.

    AROS_RUST_SDK=... AROS_CRATE_STORE=... script/aros-cargo.py build -p zed --bin zed

AROS_RUST_SDK names an installed SDK (its aros-official-rust.json manifest,
compiler, precompiled std and C SDK); AROS_CRATE_STORE the native crate store
the patches in packaging/aros/aros-patches.toml resolve into. The wrapper
verifies the SDK's recorded hashes before and after the build, writes the
AROS-only cargo configuration to target/aros/toolchain.toml, re-pins the
patched crates in the AROS lockfile (packaging/aros/Cargo.lock; the root
Cargo.lock is left to the other platforms) and runs the SDK's cargo.
"""
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

# Versions the patched crates must resolve to (see aros-patches.toml). A pin
# replaces only the semver-compatible locked versions of its crate, so other
# generations in the graph (errno 0.2, getrandom 0.2/0.3) keep their own pins.
PINS = {
    "libc": ["0.2.190"],
    "memmap2": ["0.9.10"],
    "ctor": ["1.0.12"],
    "inventory": ["0.3.24"],
    "parking_lot_core": ["0.9.12"],
    "backtrace": ["0.3.76"],
    "rustix": ["1.1.4"],
    "errno": ["0.3.14"],
    "mio": ["1.2.1"],
    "tempfile": ["3.27.0"],
    "getrandom": ["0.4.3", "0.3.4", "0.2.17"],
    "socket2": ["0.6.5"],
    "stacker": ["0.1.25"],
    "libsqlite3-sys": ["0.30.1"],
    "tokio": ["1.52.1"],
    "ring": ["0.17.14"],
    "url": ["2.5.7"],
    "aws-lc-sys": ["0.45.0"],
}


def compatible(version):
    major, minor, patch = (int(part) for part in version.split("-")[0].split("."))
    return (major,) if major else (0, minor) if minor else (0, 0, patch)


def digest(path):
    with Path(path).open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def main():
    repo = Path(__file__).resolve().parents[1]
    if any("build-std" in arg for arg in sys.argv[1:]):
        raise RuntimeError("the installed SDK supplies a precompiled std; build-std is not supported")
    for name in ("AROS_RUST_SDK", "AROS_CRATE_STORE"):
        if not os.environ.get(name):
            raise RuntimeError(f"set {name}")
    prefix = Path(os.environ["AROS_RUST_SDK"]).resolve()
    store = Path(os.environ["AROS_CRATE_STORE"]).resolve()
    manifest = json.loads((prefix / "aros-official-rust.json").read_text())
    native = Path(manifest["native_build"])
    result = json.loads((native / "result.json").read_text())
    sdk, tools = Path(result["sdk"]), Path(result["crosstools"])

    def verify():
        for name, expected in manifest["installed"].items():
            if digest(prefix / name) != expected:
                raise RuntimeError("installed SDK changed: " + name)
        for name, expected in manifest["inputs"].items():
            if digest(name) != expected:
                raise RuntimeError("SDK input changed: " + name)
        for name, expected in result["precompiled_std"].items():
            if digest(native / "sysroot/lib/rustlib/aarch64-unknown-aros/lib" / name) != expected:
                raise RuntimeError("precompiled std changed: " + name)
        if digest(native / "libaros_rs_platform.a") != result["native_adapter_archive_sha256"]:
            raise RuntimeError("native platform archive changed")

    verify()
    env = os.environ.copy()
    for name in ("RUSTFLAGS", "CARGO_BUILD_TARGET", "RUSTC_WRAPPER", "RUSTC_WORKSPACE_WRAPPER",
                 "CARGO_ENCODED_RUSTFLAGS", "CARGO_TARGET_AARCH64_UNKNOWN_AROS_LINKER",
                 "CARGO_TARGET_AARCH64_UNKNOWN_AROS_RUSTFLAGS"):
        env.pop(name, None)
    env.update(RUSTC=str(prefix / "bin/rustc"), RUSTDOC=str(prefix / "bin/rustdoc"),
               CARGO_INCREMENTAL="0", AROS_SDK=str(sdk))

    tables = tomllib.loads((repo / "packaging/aros/aros-patches.toml").read_text())["patch"]
    lines = ["# Generated by script/aros-cargo.py"]

    def entries(patches):
        for name, item in patches.items():
            source = store / item["path"]
            if not (source / "Cargo.toml").is_file():
                raise RuntimeError("missing native crate: " + str(source))
            fields = "path = " + json.dumps(str(source))
            if "package" in item:
                fields += ", package = " + json.dumps(item["package"])
            lines.append(name + " = { " + fields + " }")

    lines.append("[patch.crates-io]")
    entries(tables.pop("crates-io"))
    libc = store / ("libc-" + PINS["libc"][0])
    if not (libc / "Cargo.toml").is_file():
        raise RuntimeError("missing native libc: " + str(libc))
    lines.append("libc = { path = " + json.dumps(str(libc)) + " }")
    # Git dependencies, by repository URL.
    for source, patches in tables.items():
        lines.append("[patch." + json.dumps(source) + "]")
        entries(patches)
    lines += ["", "[env]", "AROS_SDK = " + json.dumps(str(sdk)),
              "CC_aarch64_unknown_aros = " + json.dumps(str(tools / "bin/clang")),
              "AR_aarch64_unknown_aros = " + json.dumps(str(tools / "bin/llvm-ar")),
              # OPENSSL_NO_SOCK: aws-lc leaves out its BIO socket layer, which
              # rustls never uses; the AROS C library has no socket calls yet
              # (sockets are bsdsocket.library calls).
              "CFLAGS_aarch64_unknown_aros = " + json.dumps(
                  "--target=aarch64-unknown-aros --sysroot=" + str(sdk) +
                  " -fno-pic -mcmodel=large -D_GNU_SOURCE -DHAVE_ENDIAN_H -Dasm=__asm__"
                  " -DSQLITE_OMIT_WAL=1 -DSQLITE_MAX_MMAP_SIZE=0 -DSQLITE_OMIT_LOAD_EXTENSION=1"
                  " -DOPENSSL_NO_SOCK"
                  " -O2 -Wno-pointer-sign")]
    generated = repo / "target/aros"
    generated.mkdir(parents=True, exist_ok=True)
    config = generated / "toolchain.toml"
    config.write_text("\n".join(lines) + "\n")
    env.update(tomllib.loads(config.read_text())["env"])

    # The AROS graph has its own lockfile: its patched crates resolve to store
    # paths and AROS pins, which the root Cargo.lock of the other platforms
    # must not carry. A missing one starts from the root lockfile.
    aros_lock = repo / "packaging/aros/Cargo.lock"
    if not aros_lock.is_file():
        shutil.copyfile(repo / "Cargo.lock", aros_lock)
    command = [str(prefix / "bin/cargo"), "--config", str(prefix / "cargo-config.toml"), "--config", str(config),
               "--config", "resolver.lockfile-path=" + json.dumps(str(aros_lock))]
    lock = tomllib.loads(aros_lock.read_text())
    for name, versions in PINS.items():
        for version in versions:
            for locked in sorted({p["version"] for p in lock["package"] if p["name"] == name}):
                if locked != version and compatible(locked) == compatible(version):
                    subprocess.run(command + ["update", "-p", f"{name}@{locked}", "--precise", version],
                                   cwd=repo, env=env, check=True)
    completed = subprocess.run(command + sys.argv[1:], cwd=repo, env=env)
    verify()
    return completed.returncode


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, KeyError, ValueError, RuntimeError, subprocess.CalledProcessError) as error:
        print("aros-cargo: " + str(error), file=sys.stderr)
        raise SystemExit(2)
